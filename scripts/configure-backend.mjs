// Run with the backend_url output from Terraform before building the Mac and Windows apps.
import { writeFileSync } from 'node:fs';
const url = new URL(process.argv[2]);
if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash || url.pathname !== '/') {
  throw new Error('Expected an HTTPS backend origin.');
}
writeFileSync(new URL('../src/backend.js', import.meta.url),
  `// Generated by scripts/configure-backend.mjs. Public endpoint; no credentials.\nconst BACKEND_URL = ${JSON.stringify(url.origin)};\n`);
